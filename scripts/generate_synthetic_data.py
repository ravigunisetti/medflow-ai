def generate_phcs():
    """Generates 100 PHCs across 5 districts with realistic coordinates and populations."""
    phcs = []
    phc_id = 1
    name_idx = 0
    
    for dist in DISTRICT_CONFIGS:
        for _ in range(dist["phc_count"]):
            # Small random jitter around district center (~0.05 to 0.3 degrees, roughly 5-35 km)
            lat_jitter = (random.random() - 0.5) * 0.45
            lon_jitter = (random.random() - 0.5) * 0.45
            lat = round(dist["center_lat"] + lat_jitter, 6)
            lon = round(dist["center_lon"] + lon_jitter, 6)
            
            # Log-normal distribution for rural/semi-urban population served
            pop = int(random.lognormvariate(10.35, 0.25))  # mean around 32,000
            
            prefix = PHC_NAME_PREFIXES[name_idx % len(PHC_NAME_PREFIXES)]
            suffix = f"PHC-{phc_id}"
            name = f"{prefix} {suffix}"
            name_idx += 1
            
            phcs.append({
                "id": phc_id,
                "name": name,
                "district": dist["name"],
                "state": "Maharashtra",
                "latitude": lat,
                "longitude": lon,
                "population_served": pop,
                "is_active": True,
            })
            phc_id += 1
            
    return phcs

def generate_medicines():
    """Maps essential medicine list with sequential primary keys."""
    medicines = []
    for idx, med in enumerate(MEDICINES_CATALOG, start=1):
        item = dict(med)
        item["id"] = idx
        medicines.append(item)
    return medicines

def generate_historical_series(phcs, medicines, days=365):
    """
    Generates 365 days of correlated daily footfall and medicine demand.
    - Monday surges, Sunday drop.
    - Monsoon surge (June-Sept).
    - Disease spikes and acute emergency episodes.
    """
    end_date = date.today() - timedelta(days=1)
    start_date = end_date - timedelta(days=days - 1)
    
    footfalls = []
    demands = []
    
    footfall_id = 1
    demand_id = 1
    
    # Pre-calculate outbreak events (specific PHCs experiencing 3-7 day acute outbreaks)
    outbreaks = {}
    for phc in phcs:
        outbreaks[phc["id"]] = []
        if random.random() < 0.6:  # 60% of PHCs had 1 or 2 acute episodes during the year
            num_episodes = random.choice([1, 2])
            for _ in range(num_episodes):
                outbreak_day = random.randint(30, days - 30)
                outbreak_duration = random.randint(3, 7)
                outbreak_type = random.choice(["gastro", "viral_fever", "respiratory"])
                outbreaks[phc["id"]].append((outbreak_day, outbreak_duration, outbreak_type))

    print(f"Generating {days} days of time series for {len(phcs)} PHCs...")
    
    for day_offset in range(days):
        current_date = start_date + timedelta(days=day_offset)
        weekday = current_date.weekday()  # 0=Mon, 6=Sun
        month = current_date.month
        is_monsoon = 6 <= month <= 9
        is_winter = month in [11, 12, 1]
        
        # Day-of-week multiplier
        if weekday == 0:  # Monday rush
            dow_mult = 1.25
        elif weekday == 6:  # Sunday minimum staff/OPD
            dow_mult = 0.55
        elif weekday in [1, 2]:
            dow_mult = 1.08
        else:
            dow_mult = 0.95
            
        # Seasonal footfall multiplier
        season_mult = 1.0
        if is_monsoon:
            season_mult += 0.28
        elif is_winter:
            season_mult += 0.12
            
        for phc in phcs:
            p_id = phc["id"]
            base_daily_patients = phc["population_served"] * 0.0045  # ~140 patients/day
            
            # Check for active outbreak
            outbreak_mult = 1.0
            active_outbreak_type = None
            for ob_day, ob_dur, ob_type in outbreaks[p_id]:
                if ob_day <= day_offset < ob_day + ob_dur:
                    outbreak_mult = 1.65
                    active_outbreak_type = ob_type
                    break
                    
            # Add Gaussian noise
            daily_patients = int(max(15, random.gauss(
                base_daily_patients * dow_mult * season_mult * outbreak_mult,
                base_daily_patients * 0.10
            )))
            
            emergency_count = int(max(0, random.gauss(daily_patients * 0.06, 2)))
            
            footfalls.append({
                "id": footfall_id,
                "phc_id": p_id,
                "record_date": str(current_date),
                "patient_count": daily_patients,
                "emergency_count": emergency_count,
            })
            footfall_id += 1
            
            # Generate medicine consumption correlated with footfall
            for med in medicines:
                m_id = med["id"]
                rate = med["base_demand_rate"]
                med_seasonality = med["seasonality"]
                
                med_mult = 1.0
                if is_monsoon and med_seasonality == "monsoon":
                    med_mult *= 1.75
                elif is_winter and med_seasonality == "winter":
                    med_mult *= 1.50
                    
                # Outbreak boost
                if active_outbreak_type == "gastro" and med["code"] in ["MED-007", "MED-008", "MED-003"]:  # ORS, Zinc, Cipro
                    med_mult *= 2.4
                elif active_outbreak_type == "viral_fever" and med["code"] in ["MED-005", "MED-001"]:  # Paracetamol, Amoxicillin
                    med_mult *= 2.1
                elif active_outbreak_type == "respiratory" and med["code"] in ["MED-001", "MED-002", "MED-020"]:  # Antibiotics, Inhaler
                    med_mult *= 2.2
                    
                expected_demand = daily_patients * rate * med_mult
                actual_demand = int(max(0, round(random.gauss(expected_demand, max(1.0, expected_demand * 0.18)))))
                
                demands.append({
                    "id": demand_id,
                    "phc_id": p_id,
                    "medicine_id": m_id,
                    "record_date": str(current_date),
                    "quantity_used": actual_demand,
                })
                demand_id += 1

    return footfalls, demands

def generate_current_inventories(phcs, medicines, demands):
    """
    Computes realistic current stock balances based on average daily demand.
    Engineers 3 distinct profiles for realistic redistribution simulation:
    - 15 PHCs: CRITICAL DEFICIT (1-3 days of stock remaining)
    - 10 PHCs: SURPLUS OVERSTOCK (30-60 days of stock remaining)
    - 75 PHCs: BALANCED / SAFE (10-20 days of stock remaining)
    """
    # Calculate average daily demand over the last 30 days per (phc, med)
    recent_demand = {}
    for d in demands[-len(phcs) * len(medicines) * 30:]:
        key = (d["phc_id"], d["medicine_id"])
        recent_demand[key] = recent_demand.get(key, 0) + d["quantity_used"]
        
    for k in recent_demand:
        recent_demand[k] = max(1.0, recent_demand[k] / 30.0)

    # Designate deficit and surplus PHCs
    critical_phc_ids = set(range(1, 16))      # PHC 1 to 15: Critical
    surplus_phc_ids = set(range(16, 26))      # PHC 16 to 25: Surplus donors
    # Remaining 75 PHCs: Balanced

    inventories = []
    inv_id = 1
    today = date.today()

    for phc in phcs:
        p_id = phc["id"]
        for med in medicines:
            m_id = med["id"]
            avg_daily = recent_demand.get((p_id, m_id), 15.0)
            
            if p_id in critical_phc_ids:
                # 1 to 3 days of stock left -> triggers CRITICAL / HIGH alerts
                days_stock = random.uniform(1.2, 3.4)
            elif p_id in surplus_phc_ids:
                # 30 to 60 days of stock -> prime candidates for transfer donor
                days_stock = random.uniform(32.0, 58.0)
            else:
                # Balanced: 12 to 22 days of stock
                days_stock = random.uniform(12.0, 22.0)
                
            qty = int(max(5, round(avg_daily * days_stock)))
            reserved = int(qty * 0.05) if p_id in surplus_phc_ids else 0
            
            # Expiry dates between 6 months and 2 years from today
            expiry_days = random.randint(180, 700)
            expiry_date = today + timedelta(days=expiry_days)
            batch = f"BATCH-2026-{m_id:02d}-{p_id:03d}"
            
            inventories.append({
                "id": inv_id,
                "phc_id": p_id,
                "medicine_id": m_id,
                "quantity": qty,
                "reserved_quantity": reserved,
                "batch_number": batch,
                "expiry_date": str(expiry_date),
            })
            inv_id += 1

    return inventories


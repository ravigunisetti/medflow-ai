def export_to_csv(filename, rows, fieldnames):
    filepath = DATA_DIR / filename
    with open(filepath, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    print(f"Exported {len(rows):,} rows -> {filepath}")

def generate_sql_seed(phcs, medicines, inventories, footfalls, demands, users):
    """Generates a standalone PostgreSQL seed_data.sql for 1-click loading."""
    sql_path = DATA_DIR / "seed_data.sql"
    print(f"Generating unified SQL seed script: {sql_path} ...")
    
    with open(sql_path, "w", encoding="utf-8") as f:
        f.write("-- PHC-NET AI: Synthetic Seed Data Script\n")
        f.write("-- Auto-generated by generate_synthetic_data.py\n\n")
        f.write("BEGIN;\n\n")
        
        # 1. PHCs
        f.write("-- Insert PHCs\n")
        for p in phcs:
            f.write(f"INSERT INTO phcs (id, name, district, state, latitude, longitude, population_served, is_active) "
                    f"VALUES ({p['id']}, '{p['name']}', '{p['district']}', '{p['state']}', {p['latitude']}, {p['longitude']}, {p['population_served']}, {str(p['is_active']).lower()});\n")
        f.write("SELECT setval('phcs_id_seq', (SELECT MAX(id) FROM phcs));\n\n")
        
        # 2. Medicines
        f.write("-- Insert Medicines\n")
        for m in medicines:
            f.write(f"INSERT INTO medicines (id, code, name, category, unit, safety_stock, shelf_life_days, requires_cold_chain) "
                    f"VALUES ({m['id']}, '{m['code']}', '{m['name']}', '{m['category']}', '{m['unit']}', {m['safety_stock']}, {m['shelf_life_days']}, {str(m['requires_cold_chain']).lower()});\n")
        f.write("SELECT setval('medicines_id_seq', (SELECT MAX(id) FROM medicines));\n\n")

        # 3. Users
        f.write("-- Insert Users\n")
        for u in users:
            phc_val = u['assigned_phc_id'] if u['assigned_phc_id'] is not None else 'NULL'
            dist_val = f"'{u['assigned_district']}'" if u['assigned_district'] is not None else 'NULL'
            f.write(f"INSERT INTO users (id, username, password_hash, full_name, email, role, assigned_phc_id, assigned_district, is_active) "
                    f"VALUES ({u['id']}, '{u['username']}', '{u['password_hash']}', '{u['full_name']}', '{u['email']}', '{u['role']}', {phc_val}, {dist_val}, {str(u['is_active']).lower()});\n")
        f.write("SELECT setval('users_id_seq', (SELECT MAX(id) FROM users));\n\n")

        # 4. Current Inventories
        f.write("-- Insert Current Inventories\n")
        for inv in inventories:
            f.write(f"INSERT INTO inventories (id, phc_id, medicine_id, quantity, reserved_quantity, batch_number, expiry_date) "
                    f"VALUES ({inv['id']}, {inv['phc_id']}, {inv['medicine_id']}, {inv['quantity']}, {inv['reserved_quantity']}, '{inv['batch_number']}', '{inv['expiry_date']}');\n")
        f.write("SELECT setval('inventories_id_seq', (SELECT MAX(id) FROM inventories));\n\n")

        # 5. Historical Footfalls (Batched)
        f.write("-- Insert Patient Footfalls (Recent sample in seed script, complete history in CSV)\n")
        # For seed_data.sql file size safety, output the last 30 days into SQL directly, 
        # while all 365 days are preserved in patient_footfalls.csv
        recent_footfalls = footfalls[-len(phcs) * 30:]
        for ff in recent_footfalls:
            f.write(f"INSERT INTO patient_footfalls (id, phc_id, record_date, patient_count, emergency_count) "
                    f"VALUES ({ff['id']}, {ff['phc_id']}, '{ff['record_date']}', {ff['patient_count']}, {ff['emergency_count']});\n")
        f.write("SELECT setval('patient_footfalls_id_seq', (SELECT MAX(id) FROM patient_footfalls));\n\n")

        # 6. Historical Demands (Last 30 days in SQL, complete 365 days in demands.csv)
        f.write("-- Insert Demands (Recent 30 days sample in seed script, complete history in CSV)\n")
        recent_demands = demands[-len(phcs) * len(medicines) * 30:]
        for dm in recent_demands:
            f.write(f"INSERT INTO demands (id, phc_id, medicine_id, record_date, quantity_used) "
                    f"VALUES ({dm['id']}, {dm['phc_id']}, {dm['medicine_id']}, '{dm['record_date']}', {dm['quantity_used']});\n")
        f.write("SELECT setval('demands_id_seq', (SELECT MAX(id) FROM demands));\n\n")

        f.write("COMMIT;\n")

    print(f"Unified SQL seed generated at: {sql_path}")

